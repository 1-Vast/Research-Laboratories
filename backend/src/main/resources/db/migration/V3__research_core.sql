-- =====================================================================
-- LabFlow 科研实验室智能协同管理平台 - 建表脚本（第二阶段：科研业务核心）
-- 目标数据库：PostgreSQL 14+；本地开发/测试使用 H2 2.x（MODE=PostgreSQL）
-- 全部语句保持 PostgreSQL 兼容子集，保证一套脚本两端可执行。
--
-- 表清单（7 张）：
--   projects           科研项目（聚合根）
--   project_members    项目成员（负责人 / 成员）
--   project_reviews    立项与结项审批轨迹（只增不改）
--   tasks              科研任务
--   task_submissions   任务交付快照（历史不覆盖）
--   reports            进度周报
--   report_tasks       周报关联任务（多对多）
-- =====================================================================

-- ---------------------------------------------------------------------
-- 1. projects 科研项目
-- ---------------------------------------------------------------------
CREATE TABLE projects (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lab_id        BIGINT       NOT NULL,
    leader_id     BIGINT       NOT NULL,
    name          VARCHAR(150) NOT NULL,
    objective     VARCHAR(2000),
    status        VARCHAR(32)  NOT NULL,
    planned_start DATE,
    planned_end   DATE,
    close_note    VARCHAR(2000),
    version       INT          NOT NULL DEFAULT 0,
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_projects_lab FOREIGN KEY (lab_id) REFERENCES labs (id) ON DELETE RESTRICT,
    CONSTRAINT fk_projects_leader FOREIGN KEY (leader_id) REFERENCES users (id) ON DELETE RESTRICT,
    CONSTRAINT ck_projects_status CHECK (status IN ('DRAFT', 'PENDING', 'ACTIVE', 'CLOSING', 'ARCHIVED', 'REJECTED')),
    CONSTRAINT ck_projects_plan CHECK (planned_start IS NULL OR planned_end IS NULL OR planned_end >= planned_start)
);

CREATE INDEX idx_projects_lab_status ON projects (lab_id, status);
CREATE INDEX idx_projects_leader ON projects (leader_id);

COMMENT ON TABLE projects IS '科研项目聚合根；状态迁移只允许走命令接口，禁止通用 PATCH 改 state';

-- ---------------------------------------------------------------------
-- 2. project_members 项目成员
-- ---------------------------------------------------------------------
CREATE TABLE project_members (
    project_id  BIGINT      NOT NULL,
    user_id     BIGINT      NOT NULL,
    member_type VARCHAR(16) NOT NULL,
    active      BOOLEAN     NOT NULL DEFAULT TRUE,
    joined_at   TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT pk_project_members PRIMARY KEY (project_id, user_id),
    CONSTRAINT fk_project_members_project FOREIGN KEY (project_id) REFERENCES projects (id) ON DELETE CASCADE,
    CONSTRAINT fk_project_members_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE RESTRICT,
    CONSTRAINT ck_project_members_type CHECK (member_type IN ('LEADER', 'MEMBER'))
);

CREATE INDEX idx_project_members_user ON project_members (user_id);

COMMENT ON TABLE project_members IS '项目成员；LEADER 记录由创建项目时同步写入，服务层保证每个项目只有一个有效负责人';

-- ---------------------------------------------------------------------
-- 3. project_reviews 立项 / 结项审批轨迹
-- ---------------------------------------------------------------------
CREATE TABLE project_reviews (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id  BIGINT       NOT NULL,
    review_type VARCHAR(16)  NOT NULL,
    reviewer_id BIGINT       NOT NULL,
    decision    VARCHAR(16)  NOT NULL,
    reason      VARCHAR(1000),
    reviewed_at TIMESTAMP WITH TIME ZONE NOT NULL,
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_project_reviews_project FOREIGN KEY (project_id) REFERENCES projects (id) ON DELETE CASCADE,
    CONSTRAINT fk_project_reviews_reviewer FOREIGN KEY (reviewer_id) REFERENCES users (id) ON DELETE RESTRICT,
    CONSTRAINT ck_project_reviews_type CHECK (review_type IN ('INIT', 'CLOSE')),
    CONSTRAINT ck_project_reviews_decision CHECK (decision IN ('APPROVE', 'REJECT'))
);

CREATE INDEX idx_project_reviews_project ON project_reviews (project_id, created_at);

COMMENT ON TABLE project_reviews IS '审批轨迹只增不改；用于答辩时展示“谁在什么时候批准/驳回、理由是什么”';

-- ---------------------------------------------------------------------
-- 4. tasks 科研任务
-- ---------------------------------------------------------------------
CREATE TABLE tasks (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id    BIGINT       NOT NULL,
    assignee_id   BIGINT       NOT NULL,
    title         VARCHAR(150) NOT NULL,
    description   VARCHAR(4000),
    status        VARCHAR(32)  NOT NULL,
    priority      VARCHAR(16)  NOT NULL DEFAULT 'NORMAL',
    due_at        TIMESTAMP WITH TIME ZONE,
    cancel_reason VARCHAR(500),
    version       INT          NOT NULL DEFAULT 0,
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_tasks_project FOREIGN KEY (project_id) REFERENCES projects (id) ON DELETE CASCADE,
    CONSTRAINT fk_tasks_assignee FOREIGN KEY (assignee_id) REFERENCES users (id) ON DELETE RESTRICT,
    CONSTRAINT ck_tasks_status CHECK (status IN ('TODO', 'IN_PROGRESS', 'SUBMITTED', 'DONE', 'RETURNED', 'CANCELED')),
    CONSTRAINT ck_tasks_priority CHECK (priority IN ('LOW', 'NORMAL', 'HIGH'))
);

CREATE INDEX idx_tasks_project_status ON tasks (project_id, status);
CREATE INDEX idx_tasks_assignee_status ON tasks (assignee_id, status);

COMMENT ON TABLE tasks IS '科研任务；进度由 DONE 数量除以非取消任务数量计算';

-- ---------------------------------------------------------------------
-- 5. task_submissions 任务交付快照
-- ---------------------------------------------------------------------
CREATE TABLE task_submissions (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    task_id       BIGINT      NOT NULL,
    author_id     BIGINT      NOT NULL,
    submission_no INT         NOT NULL,
    content       VARCHAR(4000) NOT NULL,
    review_status VARCHAR(16) NOT NULL,
    reviewer_id   BIGINT,
    review_note   VARCHAR(1000),
    reviewed_at   TIMESTAMP WITH TIME ZONE,
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_task_submissions_task FOREIGN KEY (task_id) REFERENCES tasks (id) ON DELETE CASCADE,
    CONSTRAINT fk_task_submissions_author FOREIGN KEY (author_id) REFERENCES users (id) ON DELETE RESTRICT,
    CONSTRAINT fk_task_submissions_reviewer FOREIGN KEY (reviewer_id) REFERENCES users (id) ON DELETE SET NULL,
    CONSTRAINT uq_task_submissions_no UNIQUE (task_id, submission_no),
    CONSTRAINT ck_task_submissions_status CHECK (review_status IN ('SUBMITTED', 'APPROVED', 'RETURNED'))
);

CREATE INDEX idx_task_submissions_task ON task_submissions (task_id, created_at);

COMMENT ON TABLE task_submissions IS '每次提交保留独立快照，退回后重新提交不覆盖历史';

-- ---------------------------------------------------------------------
-- 6. reports 进度周报
-- ---------------------------------------------------------------------
CREATE TABLE reports (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id  BIGINT      NOT NULL,
    author_id   BIGINT      NOT NULL,
    week_start  DATE        NOT NULL,
    work        VARCHAR(4000),
    blockers    VARCHAR(2000),
    next_plan   VARCHAR(2000),
    status      VARCHAR(16) NOT NULL,
    reviewer_id BIGINT,
    review_note VARCHAR(1000),
    version     INT         NOT NULL DEFAULT 0,
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_reports_project FOREIGN KEY (project_id) REFERENCES projects (id) ON DELETE CASCADE,
    CONSTRAINT fk_reports_author FOREIGN KEY (author_id) REFERENCES users (id) ON DELETE RESTRICT,
    CONSTRAINT fk_reports_reviewer FOREIGN KEY (reviewer_id) REFERENCES users (id) ON DELETE SET NULL,
    CONSTRAINT uq_reports_week UNIQUE (project_id, author_id, week_start),
    CONSTRAINT ck_reports_status CHECK (status IN ('DRAFT', 'SUBMITTED', 'APPROVED', 'RETURNED'))
);

CREATE INDEX idx_reports_project_status ON reports (project_id, status);

COMMENT ON TABLE reports IS '同项目同作者同周唯一；提交后正文只读，退回可重开草稿';

-- ---------------------------------------------------------------------
-- 7. report_tasks 周报关联任务（多对多）
-- ---------------------------------------------------------------------
CREATE TABLE report_tasks (
    report_id BIGINT NOT NULL,
    task_id   BIGINT NOT NULL,
    CONSTRAINT pk_report_tasks PRIMARY KEY (report_id, task_id),
    CONSTRAINT fk_report_tasks_report FOREIGN KEY (report_id) REFERENCES reports (id) ON DELETE CASCADE,
    CONSTRAINT fk_report_tasks_task FOREIGN KEY (task_id) REFERENCES tasks (id) ON DELETE CASCADE
);

CREATE INDEX idx_report_tasks_task ON report_tasks (task_id);

COMMENT ON TABLE report_tasks IS '周报与任务的多对多关联；任务必须与周报同项目（服务层校验）';
