-- =====================================================================
-- LabFlow 科研实验室智能协同管理平台 - 建表脚本（第一阶段：身份与授权）
-- 目标数据库：PostgreSQL 14+；本地开发使用 H2 2.x（MODE=PostgreSQL）
-- 全部语句保持 PostgreSQL 兼容子集，保证一套脚本两端可执行。
-- =====================================================================

-- ---------------------------------------------------------------------
-- 1. users 用户
-- ---------------------------------------------------------------------
CREATE TABLE users (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username      VARCHAR(64)  NOT NULL,
    password_hash VARCHAR(100) NOT NULL,
    email         VARCHAR(254),
    display_name  VARCHAR(80),
    enabled       BOOLEAN      NOT NULL DEFAULT TRUE,
    auth_version  INT          NOT NULL DEFAULT 0,
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_users_username UNIQUE (username)
);

COMMENT ON TABLE users IS '平台用户；密码仅存 BCrypt 哈希，auth_version 用于批量吊销令牌';

-- ---------------------------------------------------------------------
-- 2. roles 角色
-- ---------------------------------------------------------------------
CREATE TABLE roles (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code        VARCHAR(64) NOT NULL,
    name        VARCHAR(80) NOT NULL,
    description VARCHAR(255),
    protected   BOOLEAN     NOT NULL DEFAULT FALSE,
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_roles_code UNIQUE (code)
);

COMMENT ON TABLE roles IS '平台角色；protected=true 的内置角色不允许删除或改码';

-- ---------------------------------------------------------------------
-- 3. permissions 权限（接口操作码）
-- ---------------------------------------------------------------------
CREATE TABLE permissions (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code        VARCHAR(100) NOT NULL,
    description VARCHAR(200),
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_permissions_code UNIQUE (code)
);

COMMENT ON TABLE permissions IS '权限目录，权限码形如 project:update，由数据库动态读取';

-- ---------------------------------------------------------------------
-- 4. user_roles 用户-角色（多对多）
-- ---------------------------------------------------------------------
CREATE TABLE user_roles (
    user_id BIGINT NOT NULL,
    role_id BIGINT NOT NULL,
    CONSTRAINT pk_user_roles PRIMARY KEY (user_id, role_id),
    CONSTRAINT fk_user_roles_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT fk_user_roles_role FOREIGN KEY (role_id) REFERENCES roles (id) ON DELETE RESTRICT
);

CREATE INDEX idx_user_roles_role ON user_roles (role_id);

-- ---------------------------------------------------------------------
-- 5. role_permissions 角色-权限（多对多）
-- ---------------------------------------------------------------------
CREATE TABLE role_permissions (
    role_id       BIGINT NOT NULL,
    permission_id BIGINT NOT NULL,
    CONSTRAINT pk_role_permissions PRIMARY KEY (role_id, permission_id),
    CONSTRAINT fk_role_permissions_role FOREIGN KEY (role_id) REFERENCES roles (id) ON DELETE CASCADE,
    CONSTRAINT fk_role_permissions_permission FOREIGN KEY (permission_id) REFERENCES permissions (id) ON DELETE RESTRICT
);

CREATE INDEX idx_role_permissions_permission ON role_permissions (permission_id);

-- ---------------------------------------------------------------------
-- 6. auth_sessions 服务端会话（JWT 必须关联有效会话，退出即吊销）
-- ---------------------------------------------------------------------
CREATE TABLE auth_sessions (
    id           UUID PRIMARY KEY,
    user_id      BIGINT NOT NULL,
    auth_version INT    NOT NULL,
    issued_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    expires_at   TIMESTAMP WITH TIME ZONE NOT NULL,
    revoked_at   TIMESTAMP WITH TIME ZONE,
    last_used_at TIMESTAMP WITH TIME ZONE,
    client_ip    VARCHAR(64),
    user_agent   VARCHAR(255),
    CONSTRAINT fk_auth_sessions_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT ck_auth_sessions_expiry CHECK (expires_at > issued_at)
);

CREATE INDEX idx_auth_sessions_user ON auth_sessions (user_id);

COMMENT ON TABLE auth_sessions IS '服务端会话；JWT 的 sid 声明指向本表，吊销后旧令牌一律 401';

-- ---------------------------------------------------------------------
-- 7. refresh_tokens 刷新令牌（只存哈希，一次性轮换）
-- ---------------------------------------------------------------------
CREATE TABLE refresh_tokens (
    id         UUID PRIMARY KEY,
    session_id UUID NOT NULL,
    token_hash VARCHAR(64) NOT NULL,
    expires_at TIMESTAMP WITH TIME ZONE NOT NULL,
    used_at    TIMESTAMP WITH TIME ZONE,
    revoked_at TIMESTAMP WITH TIME ZONE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_refresh_tokens_hash UNIQUE (token_hash),
    CONSTRAINT fk_refresh_tokens_session FOREIGN KEY (session_id) REFERENCES auth_sessions (id) ON DELETE CASCADE
);

CREATE INDEX idx_refresh_tokens_session ON refresh_tokens (session_id);

COMMENT ON TABLE refresh_tokens IS '刷新令牌哈希；已使用记录保留到会话过期，用于复用检测';

-- ---------------------------------------------------------------------
-- 8. labs 实验室
-- ---------------------------------------------------------------------
CREATE TABLE labs (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code        VARCHAR(32)  NOT NULL,
    name        VARCHAR(120) NOT NULL,
    description VARCHAR(1000),
    enabled     BOOLEAN      NOT NULL DEFAULT TRUE,
    version     INT          NOT NULL DEFAULT 0,
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_labs_code UNIQUE (code)
);

-- ---------------------------------------------------------------------
-- 9. lab_members 实验室成员（member_type: PI / MEMBER）
-- ---------------------------------------------------------------------
CREATE TABLE lab_members (
    lab_id     BIGINT      NOT NULL,
    user_id    BIGINT      NOT NULL,
    member_type VARCHAR(16) NOT NULL,
    active     BOOLEAN     NOT NULL DEFAULT TRUE,
    joined_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT pk_lab_members PRIMARY KEY (lab_id, user_id),
    CONSTRAINT fk_lab_members_lab FOREIGN KEY (lab_id) REFERENCES labs (id) ON DELETE RESTRICT,
    CONSTRAINT fk_lab_members_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE RESTRICT,
    CONSTRAINT ck_lab_members_type CHECK (member_type IN ('PI', 'MEMBER'))
);

CREATE INDEX idx_lab_members_user ON lab_members (user_id);

-- ---------------------------------------------------------------------
-- 10. audit_events 审计事件（脱敏元数据，不含正文与令牌）
-- ---------------------------------------------------------------------
CREATE TABLE audit_events (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_id    BIGINT,
    lab_id      BIGINT,
    project_id  BIGINT,
    action      VARCHAR(80) NOT NULL,
    target_type VARCHAR(40),
    target_id   VARCHAR(64),
    result      VARCHAR(16) NOT NULL,
    trace_id    VARCHAR(64),
    metadata    VARCHAR(2000),
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_audit_events_actor FOREIGN KEY (actor_id) REFERENCES users (id) ON DELETE SET NULL
);

CREATE INDEX idx_audit_events_actor ON audit_events (actor_id, created_at);
CREATE INDEX idx_audit_events_action ON audit_events (action, created_at);

COMMENT ON TABLE audit_events IS '操作审计；记录脱敏元数据，拒绝事件也独立落库';
